// yarn.lock (Yarn 1 and 2+) and bun.lock: which files are picked, and that credentials never reach
// Apify, checked on what is actually sent.
import test from 'node:test';
import assert from 'node:assert/strict';
import { run } from '../src/main.js';
import { pickLockfiles, redactLockfile, RedactionError } from '../src/lockfiles.js';
import { fakeServer, stepEnv, captureStdout } from './fake.js';

async function go(cfg, inputs, opts) {
    const srv = await fakeServer(cfg);
    const step = stepEnv(srv.base, inputs, opts);
    const out = captureStdout();
    try {
        const code = await run(step.env, out.stream);
        return { code, st: srv.st, stdout: out.text() };
    } finally { await srv.close(); }
}
const prWith = (path, before, after) => ({
    prFiles: [{ filename: path, status: 'modified' }],
    files: { [`acme/app@BASESHA:${path}`]: before, [`acme/app@HEADSHA:${path}`]: after },
});
const startOf = (st) => st.requests.find((q) => q.method === 'POST' && q.path.startsWith('/v2/acts/'));

test('pickLockfiles: yarn.lock and bun.lock are checked; a binary bun.lockb is named, not read', () => {
    const files = [
        { filename: 'yarn.lock', status: 'modified' }, { filename: 'web/bun.lock', status: 'modified' },
        { filename: 'old/bun.lockb', status: 'modified' }, { filename: 'web/bun.lockb', status: 'modified' },
    ];
    const { checks, notes } = pickLockfiles(files, { max: 5 });
    assert.deepEqual(checks.map((c) => c.path), ['yarn.lock', 'web/bun.lock']);
    // web/bun.lockb changed next to a text bun.lock, so only old/bun.lockb gets a note.
    assert.equal(notes.length, 1);
    assert.match(notes[0], /`old\/bun\.lockb` is a binary lockfile and is not read/);
    assert.deepEqual(pickLockfiles([{ filename: 'x/bun.lockb', status: 'modified' }], { only: ['x/bun.lockb'] }).notes, ['`x/bun.lockb` is not a supported lockfile name; skipped.']);
});

const FORMATS = {
    'Yarn 1': {
        before: [
            '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
            '# yarn lockfile v1',
            '# https://deploy:SECRET@npm.corp.example/?sig=SIGNATURE',
            '',
            '"pkg@https://deploy:SECRET@npm.corp.example/pkg.tgz?sig=SIGNATURE":',
            '  version "1"',
            '  resolved "https://deploy:SECRET@npm.corp.example/pkg.tgz?sig=SIGNATURE#sha1"',
            '',
            'two@^1, two@^1.0:',
            '  version "1"',
            '  resolved "https://me:PASS@WORD@npm.corp.example/two.tgz?X-Sig=SIGNATURE"',
            '  integrity sha512-abc==',
            '  dependencies:',
            '    pkg "https://deploy:SECRET@npm.corp.example/pkg.tgz?sig=SIGNATURE"',
            '',
        ].join('\n'),
        kept: ['https://npm.corp.example/pkg.tgz#sha1', 'https://npm.corp.example/two.tgz', '"pkg@https://npm.corp.example/pkg.tgz"', '"two@^1", "two@^1.0":'],
        bump: (t) => t.replace(/version "1"/g, 'version "2"'),
    },
    'Yarn 2+': {
        before: [
            '# This file is generated by running "yarn install" inside your project.',
            '# https://deploy:SECRET@npm.corp.example/?sig=SIGNATURE',
            '',
            '__metadata:',
            '  version: 8',
            '  cacheKey: 10c0',
            '',
            '"pkg@https://deploy:SECRET@npm.corp.example/pkg.tgz?sig=SIGNATURE":',
            '  version: 1.0.0',
            '  resolution: "pkg@https://deploy:SECRET@npm.corp.example/pkg.tgz?sig=SIGNATURE"',
            '  checksum: 10c0/abc',
            '',
            '"two@npm:^1.0.0":',
            '  version: 1.0.0',
            '  resolution: "two@npm:1.0.0"',
            '',
        ].join('\n'),
        kept: ['pkg@https://npm.corp.example/pkg.tgz', 'two@npm:1.0.', '__metadata:'],
        bump: (t) => t.replace(/1\.0\.0/g, '1.0.1'),
    },
    bun: {
        before: [
            '{',
            '  "lockfileVersion": 1,',
            '  "workspaces": { "": { "name": "app", "dependencies": { "pkg": "^1" }, }, },',
            '  "packages": {',
            '    "pkg": ["pkg@1.0.0", "https://deploy:SECRET@npm.corp.example/?sig=SIGNATURE", {}, "sha512-x"],',
            '    "tar": ["tar@https://me:PASS@WORD@npm.corp.example/tar.tgz?X-Sig=SIGNATURE", {}],',
            '  },',
            '}',
            '',
        ].join('\n'),
        kept: ['"https://npm.corp.example/"', 'tar@https://npm.corp.example/tar.tgz'],
        bump: (t) => t.replace('pkg@1.0.0', 'pkg@1.0.1'),
    },
};

for (const [label, f] of Object.entries(FORMATS)) {
    const name = label === 'bun' ? 'bun.lock' : 'yarn.lock';
    test(`${label} ${name}: credentials and comments never reach Apify; hosts, paths and the file name do`, async () => {
        const r = await go(prWith(`app/${name}`, f.before, f.bump(f.before)));
        const start = startOf(r.st);
        assert.ok(start, `the lockfile was sent\n${r.stdout}`);
        for (const s of ['SECRET', 'SIGNATURE', 'PASS', 'deploy']) assert.ok(!start.body.includes(s), `${s} in the start request body`);
        const input = JSON.parse(start.body);
        assert.equal(input.lockfileName, name);
        for (const k of ['lockfileBefore', 'lockfileAfter']) for (const u of f.kept) assert.ok(input[k].includes(u), `${k} keeps ${u}\n${input[k]}`);
        // Cleaning is stable: what is sent cleans to itself.
        assert.equal(redactLockfile(input.lockfileBefore, name), input.lockfileBefore);
    });
}

const lockWith = {
    'Yarn 1': (url) => `# yarn lockfile v1\n\npkg@^1:\n  version "1"\n  resolved ${JSON.stringify(url)}\n`,
    'Yarn 2+': (url) => `__metadata:\n  version: 8\n\n"pkg@npm:^1":\n  version: 1.0.0\n  resolution: "pkg@npm:1"\n  dependencies:\n    x: ${JSON.stringify(url)}\n`,
    bun: (url) => JSON.stringify({ lockfileVersion: 1, workspaces: { '': {} }, packages: { pkg: ['pkg@1', url, {}, 's'] } }),
};
const NORM = 'deploy:SECRET@registry.example/p.tgz?sig=SIGNATURE';

test('URL spellings the Actor\'s URL parser accepts without "://" are refused in yarn.lock and bun.lock, never sent', async () => {
    const urls = [`https:\n//${NORM}`, `https:/${NORM}`, `https:${NORM}`, `HTTPS:\\\\${NORM}`, `ht\ttps:/\r/${NORM}`,
        `ws:${NORM}`, `git+https:${NORM}`, `pkg@https:${NORM}`, 'https:registry.example/p.tgz?sig=SIGNATURE', `https: //${NORM}`];
    for (const url of urls) {
        for (const [label, make] of Object.entries(lockWith)) {
            const name = label === 'bun' ? 'bun.lock' : 'yarn.lock';
            const before = make(url);
            assert.throws(() => redactLockfile(before, name), RedactionError, `${label}: ${JSON.stringify(url)}`);
            const r = await go(prWith(name, before, `${before}\n`));
            assert.equal(r.st.posts, 0, `${label} sent: ${JSON.stringify(url)}`);
            for (const q of r.st.requests) for (const w of ['SECRET', 'SIGNATURE']) assert.ok(!(q.body ?? '').includes(w), `${w} left in a request`);
            assert.match(r.st.comments[0]?.body ?? r.stdout, /was not sent: it (has URLs whose user names, passwords or query strings could not be removed with certainty|is not valid (Yarn lockfile|YAML|bun\.lock))/);
        }
    }
});

test('yarn.lock and bun.lock that do not parse, or that cleaning would make ambiguous, are not sent', async () => {
    const cases = [
        ['yarn.lock', 'pkg@^1:\n\tversion "1"\n', /is not valid Yarn lockfile/],
        ['yarn.lock', 'pkg@^1:\n  version "1\\"x"\n', /is not valid Yarn lockfile/],
        // Both keys become "a@https://h/p.tgz" once cleaned; Yarn would read that as one key twice.
        ['yarn.lock', '"a@https://u:SECRET@h/p.tgz", "a@https://h/p.tgz":\n  version "1"\n', /could not be re-serialized/],
        ['yarn.lock', '__metadata:\n  version: 8\n"a": {x: "\n', /is not valid YAML/],
        ['bun.lock', '{ "packages": { /* https://u:SECRET@h/ */ } }', /is not valid bun\.lock/],
        ['bun.lock', '{ "packages": { "a": ["a@1", "https://u:SECRET@h/"] ', /is not valid bun\.lock/],
    ];
    for (const [name, text, why] of cases) {
        assert.throws(() => redactLockfile(text, name), (e) => e instanceof RedactionError && why.test(e.message), `${name}: ${text}`);
        const r = await go(prWith(name, text, `${text}\n`));
        assert.equal(r.st.posts, 0, `${name} was sent`);
        for (const q of r.st.requests) assert.ok(!(q.body ?? '').includes('SECRET'), 'secret left in a request');
    }
});

test('yarn.lock: long space runs and long comments are read in linear time; a line over 16 KiB is refused', () => {
    const header = '# yarn lockfile v1\n\n';
    const entry = 'left-pad@^1.0.0:\n  version "1.1.0"\n  resolved "https://registry.yarnpkg.com/left-pad/-/left-pad-1.1.0.tgz"\n';
    const run = ' '.repeat(16000);
    const start = process.hrtime.bigint();
    // 64 comment lines just under the cap, each a space run; comments are not sent.
    const comments = Array.from({ length: 64 }, () => `#${run}x`).join('\n');
    assert.equal(redactLockfile(`${header}${comments}\n\n${entry}`, 'yarn.lock'), `# yarn lockfile v1\n\n"left-pad@^1.0.0":\n  "version" "1.1.0"\n  "resolved" "https://registry.yarnpkg.com/left-pad/-/left-pad-1.1.0.tgz"\n`);
    for (let i = 0; i < 64; i++) assert.throws(() => redactLockfile(`${header}a${run}b:\n`, 'yarn.lock'), RedactionError);
    const ms = Number(process.hrtime.bigint() - start) / 1e6;
    assert.ok(ms < 2000, `took ${ms} ms`);
    for (const line of [`#${' '.repeat(65536)}x`, `a${' '.repeat(65536)}b:`]) {
        assert.throws(() => redactLockfile(`${header}${line}\n`, 'yarn.lock'), RedactionError);
    }
});
